// Инициализация словаря Морзе для русского алфавита
const std::unordered_map<char, std::string> MorseCode::MorseMap =
{
    {'А', ".-"}, {'Б', "-..."}, {'В', ".--"}, {'Г', "--."},
    {'Д', "-.."}, {'Е', "."}, {'Ж', "...-"}, {'З', "--.."},
    {'И', ".."}, {'Й', ".---"}, {'К', "-.-"}, {'Л', ".-.."},
    {'М', "--"}, {'Н', "-."}, {'О', "---"}, {'П', ".--."},
    {'Р', ".-."}, {'С', "..."}, {'Т', "-"}, {'У', "..-"},
    {'Ф', "..-."}, {'Х', "...."}, {'Ц', "-.-."}, {'Ч', "---."},
    {'Ш', "----"}, {'Щ', "--.-"}, {'Ъ', ".--.-."}, {'Ы', "-.--"},
    {'Ь', "-..-"}, {'Э', "..-.."}, {'Ю', "..--"}, {'Я', ".-.-"},

    // Добавляем строчные буквы
    {'а', ".-"}, {'б', "-..."}, {'в', ".--"}, {'г', "--."},
    {'д', "-.."}, {'е', "."}, {'ж', "...-"}, {'з', "--.."},
    {'и', ".."}, {'й', ".---"}, {'к', "-.-"}, {'л', ".-.."},
    {'м', "--"}, {'н', "-."}, {'о', "---"}, {'п', ".--."},
    {'р', ".-."}, {'с', "..."}, {'т', "-"}, {'у', "..-"},
    {'ф', "..-."}, {'х', "...."}, {'ц', "-.-."}, {'ч', "---."},
    {'ш', "----"}, {'щ', "--.-"}, {'ъ', ".--.-."}, {'ы', "-.--"},
    {'ь', "-..-"}, {'э', "..-.."}, {'ю', "..--"}, {'я', ".-.-"}
};

std::string MorseCode::CharToMorse(char C)
{
    auto It = MorseMap.find(C);
    if (It != MorseMap.end())
    {
        return It->second;
    }
    return ""; // Возвращаем пустую строку для неизвестных символов
}

bool MorseCode::IsValidInput(const std::string& Text)
{
    for (char C : Text)
    {
        if (C != ' ' && MorseMap.find(C) == MorseMap.end())
        {
            return false;
        }
    }
    return true;
}

std::string MorseCode::TextToMorse(const std::string& Text)
{
    std::string Result;
    for (size_t i = 0; i < Text.length(); ++i)
    {
        char C = Text[i];
        if (C == ' ')
        {
            Result += "  "; // Два пробела между словами
        }
        else
        {
            std::string MorseChar = CharToMorse(C);
            if (!MorseChar.empty())
            {
                Result += MorseChar + " "; // Пробел между буквами
            }
        }
    }
    return Result;
}